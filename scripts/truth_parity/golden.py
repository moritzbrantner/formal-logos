"""Golden snapshots of the Python oracle (#954 slice R1).

The parity modules compare the Rust CLI with the Python implementation on
fixture checkouts. Each fixture comparison also calls `record(...)` with
the Python side's output, the Rust command line and the fixture's files.
`record` does nothing during the ordinary parity run; under
`scripts/truth_parity/record_goldens.py` it keeps every case and, when the
whole recording run passes, writes them to `truth/tests/golden/<module>/<test>.json`,
which `truth/tests/golden.rs` replays against the Rust CLI alone (no
`corpus.py`, no Lean).

What a case holds:

- `args`, `env`, `path_prepend`, `cwd`: the Rust invocation (cwd defaults to
  the fixture root);
- `tree`: the fixture checkout at the moment Rust ran, as an overlay on the
  file's `base` tree (the first case's tree), and its Git history (`git`:
  commits as overlays on their first parent, refs and HEAD) when the fixture
  is a repository; the index is not recorded (the replay resets it to HEAD);
- `externals`: directories outside the checkout that the invocation names
  (recorded exporter output, a fake `lake`, artifacts);
- Git histories and external directories are stored once per file, in its
  `shared` list, and cases name them as `{"shared": N}`;
- `expect`: the exit code Rust must return and the Python output it must
  reproduce: `stdout`/`stderr` byte for byte, `stdout_json` semantically
  (after dropping the top-level `ignore_keys`), `json_paths` (dotted paths
  into the stdout JSON), `error_message` (the `error.message` of a JSON
  error on stderr) and `files` (files the run must leave, byte for byte).
  An absent key is not compared, exactly as the parity test does not.

Normalizations, applied to arguments, environment, expected output and
file contents alike:

- the fixture root and each external directory become `⟪root⟫` and
  `⟪ext:N⟫` (their temporary paths differ on every run); the `⟪…⟫`
  markers cannot clash with fixture text, since recording fails if any
  recorded text already contains `⟪`;
- each commit id of the fixture repository becomes `⟪commit:N⟫`, N its
  position in topological order (the replay's commits have other ids);
- the Rust structure producer fingerprint (`truth/build.rs`) becomes
  `⟪producer⟫`, so an artifact Rust wrote stays fresh across Rust changes;
  `strip_producer` drops `"producer_sha256": "…",` from Rust's stdout and
  expected files before comparing, as `proposition_structure.without_producer`
  does (Python's reports and bundles have no such field);
- `scripts/*.py` files byte-identical to the repository's own copies (the
  `check` fixture copies them so the unmodified Python CLI runs) are left
  out, except the paths a case lists in `keep_repo`, which are recorded as
  references to the repository file of the same path;
- `__pycache__` directories and the paths in `exclude` are left out;
- a symbolic link is recorded as `{"symlink": target}` (its target tokenized);
- a case's `name` (the subtest description) is tokenized like the rest.

Exit codes are Rust's contract: where Rust differs from Python (`check`
exits 1 on a corpus error, Python 2) the call site passes Rust's code and
says why."""
import json
import os
import re
import shutil
import subprocess
from pathlib import Path

SCRIPTS = Path(__file__).resolve().parents[1]
REPOSITORY = SCRIPTS.parent
GOLDEN = REPOSITORY / "truth" / "tests" / "golden"
HEADER = ("Generated by scripts/truth_parity/record_goldens.py from the Python oracle (#954 R1); "
          "do not edit. Replayed by truth/tests/golden.rs.")

RECORDING = False
CASES = {}  # (module, test method) -> [case]
PRODUCER = None  # the Rust producer fingerprint, read from a Rust report when one is recorded
PRODUCER_FIELD = re.compile(r'"producer_sha256": "([0-9a-f]{64})"')


def _git(root, *args, text=True):
    return subprocess.run(["git", "-C", str(root), *args], capture_output=True, text=text, check=True).stdout


def _read(path):
    data = path.read_bytes()
    try:
        return data.decode("utf-8")
    except UnicodeDecodeError as error:
        raise AssertionError(f"golden fixtures must be UTF-8 text: {path}") from error


def _excluded(relative, exclude):
    parts = relative.split("/")
    if "__pycache__" in parts or parts[0] == ".git":
        return True
    return any(relative == item or relative.startswith(item.rstrip("/") + "/") for item in exclude)


def _repo_copy(relative, data):
    if not (relative.startswith("scripts/") and relative.endswith(".py") and relative.count("/") == 1):
        return False
    own = REPOSITORY / relative
    return own.is_file() and own.read_bytes() == data


def snapshot(directory, exclude=(), keep_repo=(), skip=()):
    """The files under `directory` (relative path -> content or `{"repo": path}`),
    its executable files and its empty directories."""
    files, executable, empty = {}, [], []
    skip = {Path(path).resolve() for path in skip}
    for current, directories, names in os.walk(directory):
        current = Path(current)
        directories[:] = sorted(name for name in directories if (current / name).resolve() not in skip)
        relative_dir = current.relative_to(directory).as_posix()
        if relative_dir != "." and _excluded(relative_dir, exclude):
            directories[:] = []
            continue
        if relative_dir != "." and not names and not directories:
            empty.append(relative_dir)
        for name in sorted(names):
            path = current / name
            relative = path.relative_to(directory).as_posix()
            if _excluded(relative, exclude):
                continue
            if path.is_symlink():
                files[relative] = {"symlink": os.readlink(path)}
                continue
            data = path.read_bytes()
            if relative in keep_repo:
                files[relative] = {"repo": relative}
            elif _repo_copy(relative, data):
                continue
            else:
                files[relative] = _read(path)
            if os.access(path, os.X_OK):
                executable.append(relative)
    return {"files": files, "executable": executable, "empty": empty}


def git_history(root, keep_repo=()):
    """The fixture repository's commits (topological order), refs and HEAD,
    without `scripts/*.py` copies of the repository's own files (as `snapshot`)."""
    listing = _git(root, "rev-list", "--all", "--topo-order", "--reverse", "--parents").split("\n")
    commits, index, trees = [], {}, {}
    for line in filter(None, listing):
        sha, *parents = line.split()
        tree = {}
        for entry in _git(root, "ls-tree", "-r", "-z", "--full-tree", sha).split("\0"):
            if not entry:
                continue
            meta, path = entry.split("\t", 1)
            mode, _, blob = meta.split()
            data = _git(root, "cat-file", "blob", blob, text=False)
            if mode == "120000":
                tree[path] = ({"symlink": data.decode("utf-8")}, False)
            elif path in keep_repo:
                tree[path] = ({"repo": path}, mode == "100755")
            elif not _repo_copy(path, data):
                tree[path] = (data.decode("utf-8"), mode == "100755")
        base = trees[parents[0]] if parents else {}
        overlay = {path: value[0] for path, value in tree.items() if base.get(path) != value}
        overlay.update({path: None for path in base if path not in tree})
        commits.append({"parents": [index[parent] for parent in parents], "overlay": overlay,
                        "executable": sorted(path for path, value in tree.items() if value[1]),
                        "message": _git(root, "log", "-1", "--format=%B", sha)})
        index[sha] = len(commits) - 1
        trees[sha] = tree
    refs = {}
    for line in filter(None, _git(root, "for-each-ref", "--format=%(refname) %(objectname)").split("\n")):
        name, sha = line.split()
        if sha in index:
            refs[name] = index[sha]
    head = subprocess.run(["git", "-C", str(root), "symbolic-ref", "-q", "HEAD"], capture_output=True,
                          text=True, check=False).stdout.strip()
    if not head:
        head = {"detached": index[_git(root, "rev-parse", "HEAD").strip()]}
    return {"commits": commits, "refs": refs, "head": head}, list(index)


class _Tokens:
    """Replaces temporary paths, commit ids and the producer fingerprint."""

    def __init__(self, root, externals, shas):
        pairs = []
        for token, path in [("⟪root⟫", root), *((f"⟪ext:{n}⟫", path) for n, path in enumerate(externals))]:
            path = Path(path)
            pairs += [(str(path), token), (str(path.resolve()), token)]
        pairs += [(sha, f"⟪commit:{n}⟫") for n, sha in enumerate(shas)]
        if PRODUCER:
            pairs.append((PRODUCER, "⟪producer⟫"))
        self.pairs = sorted(set(pairs), key=lambda pair: -len(pair[0]))

    def __call__(self, value):
        if isinstance(value, str):
            assert "⟪" not in value, f"golden token marker already in fixture text: {value[:200]!r}"
            for old, new in self.pairs:
                value = value.replace(old, new)
            return value
        if isinstance(value, list):
            return [self(item) for item in value]
        if isinstance(value, dict):
            return {self(key): self(item) for key, item in value.items()}
        return value


def _description(test):
    subtest = getattr(test, "_subtest", None)
    return subtest._subDescription() if subtest is not None else ""


def note_producer(text):
    """Remember the Rust producer fingerprint printed in a Rust report."""
    global PRODUCER
    if RECORDING and text:
        match = PRODUCER_FIELD.search(text)
        if match:
            PRODUCER = match.group(1)


def record(test, args, *, root, code, stdout=None, stderr=None, stdout_json=None, ignore_keys=("input_identity",),
           json_paths=None, error_message=None, files=None, env=None, path_prepend=(), externals=(), cwd=None,
           exclude=(), keep_repo=(), strip_producer=False, label=""):
    """Keep one golden case (only while recording): Rust run as `truth ARGS`
    on the checkout `root` must reproduce the given Python output."""
    if not RECORDING:
        return
    root = Path(root)
    tree = snapshot(root, exclude=exclude, keep_repo=keep_repo)
    git, shas = (git_history(root, keep_repo) if (root / ".git").is_dir() else (None, []))
    tokens = _Tokens(root, externals, shas)
    expect = {"code": code}
    for key, value in (("stdout", stdout), ("stderr", stderr), ("stdout_json", stdout_json),
                       ("json_paths", json_paths), ("error_message", error_message), ("files", files)):
        if value is not None:
            expect[key] = tokens(value)
    if stdout_json is not None:
        expect["ignore_keys"] = list(ignore_keys)
    if strip_producer:
        expect["strip_producer"] = True
    module = type(test).__module__.rsplit(".", 1)[-1]
    method = test._testMethodName
    name = " ".join(filter(None, [_description(test), label]))
    case = {
        "name": tokens(name), "args": tokens([str(arg) for arg in args]),
        "tree": {key: tokens(value) for key, value in tree.items()},
        "externals": [{key: tokens(value) for key, value in snapshot(path, skip=[root]).items()}
                      for path in externals],
        "expect": expect,
    }
    if git is not None:
        case["git"] = tokens(git)
    if env:
        case["env"] = tokens({key: str(value) for key, value in env.items()})
    if path_prepend:
        case["path_prepend"] = tokens([str(path) for path in path_prepend])
    if cwd is not None:
        case["cwd"] = tokens(str(cwd))
    CASES.setdefault((module, method), []).append(case)


def _overlay(base, files):
    overlay = {path: content for path, content in files.items() if base.get(path) != content}
    overlay.update({path: None for path in base if path not in files})
    return overlay


def write_all(directory=GOLDEN):
    """Write every recorded group, replacing all existing golden files."""
    if directory.exists():
        for path in directory.iterdir():
            if path.is_dir():
                shutil.rmtree(path)
    for (module, method), cases in sorted(CASES.items()):
        base = cases[0]["tree"]["files"]
        shared, index = [], {}

        def intern(value):
            # Git histories and external directories repeat across a test's
            # cases: each distinct one is stored once, under `shared`.
            key = json.dumps(value, sort_keys=True)
            if key not in index:
                index[key] = len(shared)
                shared.append(value)
            return {"shared": index[key]}

        out = []
        for case in cases:
            tree = case["tree"]
            case = dict(case, tree={"overlay": _overlay(base, tree["files"]), "executable": tree["executable"],
                                    "empty": tree["empty"]},
                        externals=[intern(external) for external in case["externals"]])
            if "git" in case:
                case["git"] = intern(case["git"])
            out.append(case)
        path = directory / module / f"{method}.json"
        path.parent.mkdir(parents=True, exist_ok=True)
        document = {"about": HEADER, "module": module, "test": method, "base": base, "shared": shared, "cases": out}
        path.write_text(json.dumps(document, indent=1, ensure_ascii=False, sort_keys=True) + "\n")
    return sorted(CASES)
